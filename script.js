// ===== Data & calculations =====
const DEFAULT_VEHICLES = [
  { key: "private", label: "Private Vehicle" }, { key: "jeepney", label: "Jeepney/Taxi/PUV" },
  { key: "bus", label: "Bus/Truck" }, { key: "motorcycle", label: "Motorcycle" }, { key: "bicycle", label: "Bicycle" },
];
let VEHICLE_KEYS = DEFAULT_VEHICLES.map((v) => v.key);
let VEHICLE_LABELS = {
  private: "Private Vehicle", jeepney: "Jeepney/Taxi/PUV", bus: "Bus/Truck",
  motorcycle: "Motorcycle", bicycle: "Bicycle",
};
const DEFAULT_SETTINGS = {
  capacity: 1800,
  vehicles: DEFAULT_VEHICLES,
  pcf: { private: 1.0, jeepney: 1.5, bus: 2.0, motorcycle: 0.5, bicycle: 0.2 },
  amFactors: [0.9, 0.85, 0.88, 0.95], // 8-9, 9-10, 10-11, 11-12 (x 7-8 AM count)
  pmFactors: [0.95, 0.9, 0.85, 0.9, 1.0], // (no longer used for PM; kept for saved settings)
  growthRate: 3,      // % annual traffic growth (Without Project)
  projectIncrease: 10 // % additional traffic generated by the project (With Project)
};
// ===== PM formula (matches pm_traffic.xlsx) =====
// Estimated PM hour = 1-2 PM actual count + (REF#2 hour - REF#2 peak)
const PM_PATTERN = {
  private:    [78 - 149, 83 - 149, 81 - 149, 151 - 149, 0],
  jeepney:    [311 - 330, 335 - 330, 345 - 330, 292 - 330, 0],
  bus:        [13 - 27, 11 - 27, 15 - 27, 11 - 27, 0],
  motorcycle: [151 - 103, 124 - 103, 149 - 103, 120 - 103, 0],
  bicycle:    [15 - 28, 11 - 28, 50 - 28, 11 - 28, 0],
};
// ===== AM formula (base = Excel Movement 1 reference) =====
// Estimated AM hour = 7-8 AM actual count + (REF hour - REF 7-8 AM)
// REF: 7-8 119/41/27/54, 8-9 48/22/13/102, 9-10 53/46/11/75, 10-11 51/56/15/100, 11-12 121/3/11/71
const AM_PATTERN = {
  private:    [48 - 119, 53 - 119, 51 - 119, 121 - 119],
  jeepney:    [22 - 41, 46 - 41, 56 - 41, 3 - 41],
  bus:        [13 - 27, 11 - 27, 15 - 27, 11 - 27],
  motorcycle: [102 - 54, 75 - 54, 100 - 54, 71 - 54],
  bicycle:    [0, 0, 0, 0],
};
const PM_PCF = { private: 1.0, jeepney: 1.5, bus: 2.0, motorcycle: 1.0, bicycle: 0.5 };
const PM_CAPACITY = 1800;
function pmLOS(vcr, hasData) {
  if (!hasData) return "—";
  if (vcr <= 0.199) return "A"; if (vcr <= 0.44) return "B"; if (vcr <= 0.69) return "C";
  if (vcr <= 0.84) return "D"; if (vcr <= 1) return "E"; return "F";
}
const HOURS = [7, 8, 9, 10, 11, 13, 14, 15, 16, 17]; // PM: 1-2 PM actual, 2-6 PM auto (same as Excel)
const ANCHOR_INDICES = [0, 5];
const STORAGE_KEY = "traffic-survey-standalone-v1";

const emptyCounts = () => Object.fromEntries(VEHICLE_KEYS.map((k) => [k, 0]));
function syncVehicles() {
  VEHICLE_KEYS = state.settings.vehicles.map((v) => v.key);
  VEHICLE_LABELS = Object.fromEntries(state.settings.vehicles.map((v) => [v.key, v.label]));
}

function formatHourRange(hour) {
  const fmt = (h) => `${((h + 11) % 12) + 1}:00 ${h < 12 ? "AM" : "PM"}`;
  return `${fmt(hour)}–${fmt(hour + 1)}`;
}
function formatDateLong(date) {
  return new Date(`${date}T00:00:00`).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });
}
const makeRows = () => HOURS.map((hour, i) => ({ hour, actual: ANCHOR_INDICES.includes(i), counts: null }));
const makeMovement = (i, name) => ({ id: `m${Date.now()}-${i}`, name: name || `Main Road ${i}`, rows: makeRows() });
const makeDataset = (date) => ({
  id: `ds-${Date.now()}`, date, location: "",
  movements: [makeMovement(1, "J.P. Rizal Street"), ...[2, 3, 4, 5, 6].map((i) => makeMovement(i))],
});

function estimatedCounts(rows, index, s) {
  const am = rows[0].counts || emptyCounts();
  const noon = rows[5].counts || emptyCounts();
  const r = emptyCounts();
  for (const k of VEHICLE_KEYS) {
    // Walang estimate kapag zero/blank pa ang ACTUAL na basehan
    const base = index < 5 ? Number(am[k]) || 0 : Number(noon[k]) || 0;
    if (base <= 0) { r[k] = 0; continue; }
    if (index < 5) r[k] = Math.max(0, base + (AM_PATTERN[k]?.[index - 1] ?? 0));
    else r[k] = Math.max(0, base + (PM_PATTERN[k]?.[index - 6] ?? 0));
  }
  return r;
}
function rowCounts(rows, i, s) {
  const row = rows[i];
  return row.actual ? { ...emptyCounts(), ...(row.counts || {}) } : estimatedCounts(rows, i, s);
}
const totalVehicles = (c) => VEHICLE_KEYS.reduce((a, k) => a + c[k], 0);
const pcu = (c, s) => VEHICLE_KEYS.reduce((a, k) => a + c[k] * (s.pcf[k] ?? 1), 0);
const volumeCapacity = (c, s) => (s.capacity > 0 ? pcu(c, s) / s.capacity : 0);
function levelOfService(vc, hasData) {
  if (!hasData) return "—";
  if (vc <= 0.6) return "A"; if (vc <= 0.7) return "B"; if (vc <= 0.8) return "C";
  if (vc <= 0.9) return "D"; if (vc <= 1.0) return "E"; return "F";
}
function aggregate(rows, s, from, to) {
  const r = emptyCounts();
  for (let i = from; i <= to; i++) { const c = rowCounts(rows, i, s); VEHICLE_KEYS.forEach((k) => (r[k] += c[k])); }
  return r;
}
function surveyId(date) {
  const compact = date.replaceAll("-", "");
  let h = 0;
  for (const ch of compact) h = (h * 31 + ch.charCodeAt(0)) & 0xffff;
  return `TS-${compact}-${h.toString(36).toUpperCase().padStart(4, "0").slice(-4)}`;
}


// ===== Summary of LOS (Without and With Project) =====
function periodVc(m, from, to) {
  let vcSum = 0, n = 0, any = false;
  for (let i = from; i <= to; i++) { const r = rowCells(m, i); vcSum += r.vc; n++; if (r.hasData) any = true; }
  return { vc: n ? vcSum / n : 0, any };
}
function summaryYears(base) {
  const y = [];
  for (let i = 0; i <= 14; i++) y.push(base + i);
  [15, 20, 30, 50].forEach((o) => y.push(base + o));
  return y;
}
function losSummaryData() {
  const d = dataset(), s = state.settings;
  const base = Number((d.date || "").slice(0, 4)) || new Date().getFullYear();
  const g = (Number(s.growthRate) || 0) / 100, p = (Number(s.projectIncrease) || 0) / 100;
  const per = d.movements.map((m) => ({ am: periodVc(m, 0, 4), pm: periodVc(m, 5, 9) }));
  return summaryYears(base).map((year) => {
    const f = Math.pow(1 + g, year - base);
    const calc = (mult) => per.flatMap(({ am, pm }) => [
      levelOfService(am.vc * f * mult, am.any), pmLOS(pm.vc * f * mult, pm.any)]);
    return { year, without: calc(1), withP: calc(1 + p) };
  });
}
function losSummaryTable(cls = "") {
  const d = dataset(), rows = losSummaryData();
  const head1 = `<tr><th rowspan="2">Year</th><th rowspan="2">Condition</th>${d.movements.map((m, i) => `<th colspan="2">Movement ${i + 1}</th>`).join("")}</tr>`;
  const head2 = `<tr>${d.movements.map(() => "<th>AM</th><th>PM</th>").join("")}</tr>`;
  const body = rows.map((r) => `<tr><td rowspan="2">${r.year}</td><td>Without Project</td>${r.without.map((x) => `<td>${x}</td>`).join("")}</tr>
    <tr><td>With Project</td>${r.withP.map((x) => `<td>${x}</td>`).join("")}</tr>`).join("");
  return `<table class="${cls}">${head1}${head2}${body}</table>`;
}

// ===== State =====
function loadState() {
  try {
    const p = JSON.parse(localStorage.getItem(STORAGE_KEY));
    if (p && p.datasets) p.datasets.forEach((d) => d.movements.forEach((m) => {
      if (m.rows.length === 11) m.rows = m.rows.filter((_, i) => i !== 6).map((r, i) => ({ ...r, hour: HOURS[i], actual: ANCHOR_INDICES.includes(i) ? true : r.actual }));
    }));
    if (p && p.datasets && p.datasets.length) return { ...p, settings: { ...DEFAULT_SETTINGS, ...p.settings } };
  } catch (e) {}
  const ds = makeDataset(new Date().toISOString().slice(0, 10));
  return { datasets: [ds], activeDatasetId: ds.id, settings: structuredClone(DEFAULT_SETTINGS) };
}
