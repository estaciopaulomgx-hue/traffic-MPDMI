const LOS_TEXT = { A: "free flow traffic", B: "free flow traffic", C: "moderate traffic", D: "heavy traffic", E: "very heavy traffic", F: "forced flow / congested" };
function wordTable(m, from, to) {
  const f = (n) => Math.round(n).toLocaleString("en-US");
  const hr = (h) => `${((h + 11) % 12) + 1}:00`;
  const keys = VEHICLE_KEYS;
  const sums = Object.fromEntries(keys.map((k) => [k, 0]));
  let vSum = 0, pSum = 0, vcSum = 0, n = 0, anyData = false;
  let body = "";
  for (let i = from; i <= to; i++) {
    const r = rowCells(m, i);
    keys.forEach((k) => (sums[k] += r.c[k]));
    vSum += r.total; pSum += r.pcuVal; vcSum += r.vc; n++; if (r.hasData) anyData = true;
    body += `<tr><td>${hr(r.row.hour)}</td><td>${hr(r.row.hour + 1)}</td>${keys.map((k) => `<td>${f(r.c[k])}</td>`).join("")}
      <td>${f(r.total)}</td><td>${f(r.pcuVal)}</td><td>${(Math.round(r.vc * 100) / 100)}</td><td>${r.los}</td></tr>`;
  }
  const avgVc = Math.round((vcSum / n) * 100) / 100;
  const los = from >= 5 ? pmLOS(avgVc, anyData) : levelOfService(avgVc, anyData);
  body += `<tr><td colspan="2"><b>Total/Average</b></td>${keys.map((k) => `<td><b>${f(sums[k])}</b></td>`).join("")}
    <td><b>${f(vSum)}</b></td><td><b>${f(pSum / n)}</b></td><td><b>${avgVc}</b></td><td><b>${los}</b></td></tr>`;
  const head = `<tr><th colspan="2">Time</th>${keys.map((k) => `<th>${esc(k === "motorcycle" ? "Motorcycle/tricycle Pedicab" : VEHICLE_LABELS[k])}</th>`).join("")}<th>V/hr.</th><th>PCU/hr</th><th>VCR</th><th>LOS</th></tr>`;
  return { html: `<table>${head}${body}</table>`, los };
}
const FORECAST_YEARS = 50; // base year + 50 succeeding years (e.g. 2026-2076)
// Projected movement: lahat ng ACTUAL rows (7-8 AM, 1-2 PM at mga na-Convert) x (1 + growth)^n
function projectMovement(m, n) {
  const f = Math.pow(1 + (Number(state.settings.growthRate) || 0) / 100, n);
  return { ...m, rows: m.rows.map((r) => ({ ...r,
    counts: r.actual && r.counts ? Object.fromEntries(Object.entries(r.counts).map(([k, v]) => [k, Math.round((Number(v) || 0) * f)])) : r.counts })) };
}
