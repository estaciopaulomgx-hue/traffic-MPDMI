// Update numbers in place (keeps focus while typing)
function refreshNumbers() {
  const m = movement();
  refreshTotals(m);
  m.rows.forEach((row, i) => {
    const r = rowCells(m, i);
    const set = (sel, v) => { const el = document.querySelector(`[data-f="${sel}"]`); if (el) el.textContent = v; };
    set(`total-${i}`, r.total); set(`pcu-${i}`, r.pcuVal.toFixed(1).replace(/\.0$/, ""));
    set(`vc-${i}`, r.vc.toFixed(2)); set(`los-${i}`, r.los);
    if (!row.actual) VEHICLE_KEYS.forEach((k) => { const el = document.querySelector(`[data-est="${i}-${k}"]`); if (el) el.textContent = r.c[k]; });
  });
}

// TOTAL rows (AM, PM, whole day) under the counts table
function totalsRow(m) {
  const line = (label, from, to, id) => {
    const c = aggregate(m.rows, state.settings, from, to);
    return `<tr class="total-row"><td colspan="2" class="bold">${label}</td>
      ${VEHICLE_KEYS.map((k) => `<td class="bold" data-f="tot-${id}-${k}">${c[k]}</td>`).join("")}
      <td class="bold" data-f="tot-${id}-all">${totalVehicles(c)}</td><td colspan="4"></td></tr>`;
  };
  return `<tfoot>${line("Total AM (7–12)", 0, 4, "am")}${line("Total PM (1–6)", 5, 9, "pm")}${line("Grand Total", 0, 9, "day")}</tfoot>`;
}
function refreshTotals(m) {
  [["am", 0, 4], ["pm", 5, 9], ["day", 0, 9]].forEach(([id, a, b]) => {
    const c = aggregate(m.rows, state.settings, a, b);
    VEHICLE_KEYS.forEach((k) => { const el = document.querySelector(`[data-f="tot-${id}-${k}"]`); if (el) el.textContent = c[k]; });
    const el = document.querySelector(`[data-f="tot-${id}-all"]`); if (el) el.textContent = totalVehicles(c);
  });
}

