function rowCells(m, i) {
  const s = state.settings, row = m.rows[i];
  const c = rowCounts(m.rows, i, s), total = totalVehicles(c);
  const hasData = row.actual ? row.counts !== null : total > 0;
  if (i >= 5) {
    const p = VEHICLE_KEYS.reduce((a, k) => a + c[k] * (PM_PCF[k] ?? state.settings.pcf[k] ?? 1), 0);
    const vc = Math.round((total / PM_CAPACITY) * 100) / 100;
    return { c, total, vc, hasData, row, pcuVal: p, los: pmLOS(vc, hasData) };
  }
  // AM: same as Excel — VCR = V/hr ÷ 1800 (2 decimals), PCU rounded
  const vc = Math.round((total / PM_CAPACITY) * 100) / 100;
  return { c, total, vc, hasData, row, pcuVal: Math.round(pcu(c, s)), los: pmLOS(vc, hasData) };
}

